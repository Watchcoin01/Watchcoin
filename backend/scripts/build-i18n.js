// Builds public/i18n.js from i18n/*.json. Run after editing any translation: npm run i18n
// It fails if a language is missing a text or changes a {placeholder}, so the app never shows a raw key.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'i18n');
const LANGS = [['en', 'English'], ['fr', 'Français'], ['es', 'Español'], ['zh', '中文'], ['sw', 'Kiswahili'], ['ha', 'Hausa'], ['tw', 'Twi']];
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
const holes = (s) => (s.match(/\{\w+\}/g) || []).sort().join(',');

function check(strings) {
  const en = strings.en, problems = [];
  for (const [code] of LANGS) {
    const d = strings[code];
    for (const part of ['ui', 'srv']) {
      for (const k of Object.keys(en[part])) {
        if (typeof d[part][k] !== 'string' || !d[part][k].trim()) problems.push(`${code}.${part}: missing "${k}"`);
        else if (holes(d[part][k]) !== holes(en[part][k])) problems.push(`${code}.${part}: placeholders differ in "${k}"`);
      }
      for (const k of Object.keys(d[part])) if (!(k in en[part])) problems.push(`${code}.${part}: unknown key "${k}"`);
    }
  }
  return problems;
}

function build() {
  const strings = Object.fromEntries(LANGS.map(([c]) => [c, read(`${c}.json`)]));
  const problems = check(strings);
  if (problems.length) throw new Error('Translation problems:\n' + problems.join('\n'));
  const geo = read('geo.json');
  const out = { LANGS: LANGS.map(([code, name]) => ({ code, name })), STR: strings, TZ: geo.tz, COUNTRY_LANG: geo.cl, COUNTRIES: geo.countries };
  const js = '/* Generated by scripts/build-i18n.js from the i18n/ folder. Edit those files, not this one. */\nwindow.WCI18N = ' + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'public', 'i18n.js'), js);
  return { bytes: js.length, keys: Object.keys(strings.en.ui).length + Object.keys(strings.en.srv).length };
}

if (require.main === module) { const r = build(); console.log(`public/i18n.js written: ${r.keys} texts x ${LANGS.length} languages, ${Math.round(r.bytes / 1024)} KB`); }
module.exports = { build, check, LANGS };
